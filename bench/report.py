"""Append executed evidence, retaining stored precision and raw summaries."""
import pathlib,json,sys,subprocess
root=pathlib.Path(sys.argv[1]);title=sys.argv[2]
dirs=sorted(p.parent for p in root.glob('*/reconciliation.json'))
assert dirs,'No completed runs'
lines=['\n## '+title+'\n','Each row is an executed run. Error rate is k6 HTTP failure fraction; expected sold-out/idempotent statuses do not count as failures. Latencies are milliseconds, from full-precision k6 exports. Threshold failures remain in the table and raw files.\n',
'| Run | req/s | p50 | p95 | p99 | errors | HTTP 202 | CONFIRMED | stock | oversold | lost | duplicates | stuck | k6 exit |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|---|']
for d in dirs:
 s=json.loads((d/'summary.json').read_text())['metrics'];r=json.loads((d/'reconciliation.json').read_text());l=s['http_req_duration']
 assert s.get('accepted_orders',{}).get('count',0)==r['http_202']
 values=[d.name,s['http_reqs']['rate'],l['med'],l['p(95)'],l['p(99)'],s['http_req_failed']['value'],r['http_202'],r['confirmed'],r['redis_stock'],r['oversold_count'],r['lost_orders'],r['duplicate_orders'],r['stuck_reservations'],r['k6_exit']]
 lines.append('| '+' | '.join(map(str,values))+' |')
lines.append('\nMaximum observed per-container snapshots (Docker display precision; not guaranteed peaks), generated by executed `python3 bench/summarize.py '+str(root)+'`:\n\n```text')
summary=subprocess.check_output(['python3','bench/summarize.py',str(root)],text=True)
(root/'summary-exact.log').write_text(summary)
lines.append('\n'.join(l for l in summary.splitlines() if 'container' in l));lines.append('```')
for d in dirs:
 lines.append('\n### '+d.name+' raw output\n')
 lines.append('Commands, revision, configuration, accepted-key ledger, Postgres rows, Redis reservations and resource snapshots: ['+d.name+']('+str(d)+'/).\n')
 git=(d/'git.txt').read_text(); k=(d/'k6.log').read_text();start=k.find('  █ THRESHOLDS')
 if start<0:start=k.find('  █ TOTAL RESULTS')
 lines.extend(['```text',git,k[start:] if start>=0 else k,'```','\nReconciliation:\n','```json',(d/'reconciliation.json').read_text(),'```'])
 for fault in d.glob('fault-*.log'):lines.extend(['\n```text',fault.read_text(),'```'])
 lines.extend(['\nQueue drain final output (full polling output retained):\n','```text','\n'.join((d/'drain.log').read_text().splitlines()[-6:]),'```'])

ooms=[];throttles=[]
for d in dirs:
 ins=(d/'inspect.log').read_text();objects=json.loads(ins[ins.index('['):ins.rindex(']')+1])
 ooms.extend((d.name,o['Name'],o['State']['OOMKilled']) for o in objects)
 for p in d.glob('*-cgroup-*.txt'):
  text=p.read_text()
  for field in ['nr_throttled','throttled_usec','oom','oom_kill']:
   for line in text.splitlines():
    if line.startswith(field+' '):throttles.append((d.name,p.name,line))
lines.append('')
lines.append('\nOOMKilled flags from executed Docker inspect:\n\n```text\n'+'\n'.join(map(str,ooms))+'\n```')
lines.append('\nCPU throttling and memory OOM counters (raw before/after cgroup snapshots):\n\n```text\n'+'\n'.join(map(str,throttles))+'\n```')
with pathlib.Path('RESULTS.md').open('a') as f:f.write('\n'.join(lines)+'\n')
